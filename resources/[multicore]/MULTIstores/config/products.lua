-- ============================================================
-- MULTIstores :: what each store type sells and buys
-- The same item shape rsg-inventory's CreateShop uses (RSG v2, GPL v3):
--   name        item name (must exist in MULTIinventory's registry; unknown names are skipped with a warning)
--   price       what the player pays, dollars with cents (nil = the store does not sell it; 0 = free)
--   amount      stock (nil = never runs out)
--   restock     stock added back each restock (default: filled up to `amount`)
--   buyPrice    what the store pays the player for one (nil = the store does not buy it)
--   maxStock    the store stops buying when its stock of the item reaches this
--   minQuality  the store only buys items whose info.quality is at least this
--   category    tab on the store screen (default: from the item; locale key cat_<category>)
--   info        item info given with each one bought
--
-- Prices are 1899-level (RINGO's decision, 2026-11-18): RDR2's own store prices where they
-- are known (the game is set in 1899), otherwise historical prices of the late 1890s
-- (a loaf of bread 5-10 cents, a glass of beer 5 cents, a bottle of whiskey about $1,
-- a cigar 5-10 cents). The old economy SPEC is no longer the price source for MULTIcore.
-- No money loops: a store never buys an item back for more than half of the lowest price
-- it is sold for anywhere (a warning is printed at start otherwise).
-- Trapper and butcher pay-outs are at RDR2's own level (a perfect pelt pays a few dollars).
-- 'gunsmith' is not listed here: it is built from MULTIinventory's weapon data with the
-- prices in config/gunsmith.lua.
-- ============================================================

